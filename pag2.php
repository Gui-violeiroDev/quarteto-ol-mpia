        <h2>Biografia</h2>
        <p>
            O Quarteto Olympia foi criado em 2019 com o objetivo principal de se divertir fazendo música juntos, 
            além do envolvimento que já tinham dentro da Orquestra.
            A ideia para o nome do quarteto surgiu a partir da inspiração em um famoso grupo de amigos conhecido como Academia Olympia, 
            do qual fazia parte o renomado físico Albert Einstein. A conexão veio do fato de que Einstein também era violinista, 
            e seu grupo costumava se reunir para conversar sobre física e filosofia, todos com algum tipo de relação com a música.
            Acreditamos que a música é a arte suprema, pois tem o poder de despertar diferentes sensações e emoções em quem a ouve.
            Foi com esse pensamento que nasceu o Quarteto Olympia: queremos proporcionar ao público uma música de qualidade, 
            capaz de despertar bons sentimentos, além de levar cultura e oferecer a oportunidade de conhecer um pouco mais do universo dos instrumentos eruditos
        </p>
